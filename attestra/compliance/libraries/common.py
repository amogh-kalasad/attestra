"""Shared helpers for external control library importers."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

PACKS_DIR = Path(__file__).resolve().parent.parent / "data" / "packs"
_KEY_RE = re.compile(r"^[a-z][a-z0-9_]{1,63}$")


@dataclass
class ImportedLibrary:
    framework: str
    name: str
    source: str
    titles: dict[str, str] = field(default_factory=dict)
    controls: dict[str, list[str]] = field(default_factory=dict)
    unmapped: list[str] = field(default_factory=list)

    def add(self, objective: str, ref: str) -> None:
        refs = self.controls.setdefault(objective, [])
        if ref not in refs:
            refs.append(ref)

    def to_pack(self) -> dict:
        return {
            "framework": self.framework,
            "name": self.name,
            "pack": f"{self.name} (imported from {self.source})",
            "controls": {k: sorted(v) for k, v in sorted(self.controls.items()) if v},
            "titles": dict(sorted(self.titles.items())),
        }

    def summary(self) -> dict:
        mapped = sorted({r for refs in self.controls.values() for r in refs})
        return {
            "framework": self.framework,
            "name": self.name,
            "source": self.source,
            "controls_in_catalog": len(self.titles),
            "controls_mapped": len(mapped),
            "objectives_covered": len([k for k, v in self.controls.items() if v]),
            "unmapped": len(self.unmapped),
        }


def check_framework_key(key: str) -> str:
    if not _KEY_RE.match(key or ""):
        raise ValueError(f"framework key {key!r} must be lower_snake_case (letters, digits, _)")
    return key


def hub_objectives() -> dict:
    from attestra.compliance.engine import load_library

    return load_library().objectives


def validate_pack(pack: dict, objectives: dict | None = None, existing: set[str] | None = None) -> None:
    """Raise ValueError if the pack would be rejected by the library loader."""
    objectives = hub_objectives() if objectives is None else objectives
    fw = check_framework_key(str(pack.get("framework") or ""))
    if existing and fw in existing:
        raise ValueError(f"framework {fw!r} is already defined in the control library")
    if not pack.get("name"):
        raise ValueError("pack needs a name")
    titles = pack.get("titles") or {}
    for obj, refs in (pack.get("controls") or {}).items():
        if obj not in objectives:
            raise ValueError(f"unknown objective {obj!r}")
        for ref in refs:
            if ref not in titles:
                raise ValueError(f"ref {ref!r} has no title")


def write_pack(lib: ImportedLibrary, path: Path) -> Path:
    pack = lib.to_pack()
    validate_pack(pack)
    header = (
        f"# Imported control library: {lib.name}\n"
        f"# Source: {lib.source}. Generated by `attestra library-import`.\n"
        "# Review titles and objective mappings before relying on them in an audit.\n"
    )
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump(pack, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return path


def install_pack(lib: ImportedLibrary, packs_dir: Path | None = None) -> Path:
    """Write the pack into the library's packs folder and reload the library."""
    from attestra.compliance.engine import clear_library_cache, load_library

    packs_dir = Path(packs_dir) if packs_dir else PACKS_DIR
    target = packs_dir / f"{lib.framework}.yaml"
    if target.exists() or lib.framework in load_library().frameworks:
        raise ValueError(f"framework {lib.framework!r} is already installed")
    write_pack(lib, target)
    clear_library_cache()
    return target


def load_objective_map(path: Path | None) -> dict[str, list[str]]:
    """Read an objective map YAML: ``{objective: [control id, ...]}``."""
    if not path:
        return {}
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError("objective map must be a mapping of objective -> [control ids]")
    return {str(k): [str(x) for x in (v or [])] for k, v in data.items()}


def clean(text: str, limit: int = 160) -> str:
    text = " ".join(str(text or "").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "..."
