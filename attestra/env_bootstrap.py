"""Install-time helpers that seed local secrets into a ``.env`` file.

Used by ``scripts/ensure_env_secrets.py`` and the local / Compose install wrappers.
Never overwrites a non-empty ``ATTESTRA_CREDENTIAL_FERNET_KEY``. Does not print the key.
"""

from __future__ import annotations

import os
import re
import secrets
from dataclasses import dataclass
from pathlib import Path

from cryptography.fernet import Fernet

from attestra.env_loader import REPO_ROOT, parse_env_text

FERNET_KEY_NAME = "ATTESTRA_CREDENTIAL_FERNET_KEY"
SESSION_SECRET_NAME = "ATTESTRA_SESSION_SECRET"
API_KEY_PEPPER_NAME = "ATTESTRA_API_KEY_PEPPER"
INSECURE_DEFAULTS = {
    SESSION_SECRET_NAME: "attestra-dev-session-change-me",
    API_KEY_PEPPER_NAME: "attestra-dev-pepper-change-me",
}

# Recommended local-lab flags. Existing non-empty values are left alone.
LOCAL_TESTING_FLAGS = {
    "APP_ENV": "local",
    "ATTESTRA_AUTH_WEB_ENABLED": "1",
    "ATTESTRA_AUTOMATED_VAPT_ENABLED": "1",
    "ATTESTRA_AUTH_SECRET_DIR": "/data/auth-secrets",
    "ATTESTRA_INITIAL_TEST_RUN_CREDITS": "10",
    "ATTESTRA_PUBLIC_URL": "http://127.0.0.1:8000",
}

_ASSIGN_RE = re.compile(
    rf"^(?P<prefix>\s*(?:export\s+)?)(?P<key>{re.escape(FERNET_KEY_NAME)})\s*=\s*(?P<value>.*)$"
)
_COMMENTED_ASSIGN_RE = re.compile(
    rf"^(?P<prefix>\s*)#\s*(?:export\s+)?(?P<key>{re.escape(FERNET_KEY_NAME)})\s*=\s*(?P<value>.*)$"
)


@dataclass(frozen=True)
class EnsureFernetResult:
    """Outcome of [[ensure_credential_fernet_key]]."""

    env_path: Path
    created_env_file: bool
    generated: bool
    already_set: bool


def generate_fernet_key() -> str:
    """Return a new url-safe Fernet key string (32 random bytes, base64)."""
    return Fernet.generate_key().decode("ascii")


def default_env_path(cwd: Path | None = None) -> Path:
    """Preferred ``.env`` path: cwd when it already has one, else repo root."""
    here = (cwd or Path.cwd()) / ".env"
    if here.is_file():
        return here
    root = REPO_ROOT / ".env"
    if root.is_file():
        return root
    return here if (cwd or Path.cwd()).resolve() == REPO_ROOT.resolve() else root


def default_example_path() -> Path:
    return REPO_ROOT / ".env.example"


def ensure_env_file(env_path: Path, *, example_path: Path | None = None) -> bool:
    """Create ``env_path`` from ``.env.example`` when missing. Returns True if created."""
    env_path = Path(env_path)
    if env_path.is_file():
        return False
    example = Path(example_path) if example_path is not None else default_example_path()
    env_path.parent.mkdir(parents=True, exist_ok=True)
    if example.is_file():
        env_path.write_text(example.read_text(encoding="utf-8"), encoding="utf-8")
    else:
        env_path.write_text(
            "# Attestra local environment (auto-created).\n"
            "APP_ENV=local\n"
            f"{FERNET_KEY_NAME}=\n",
            encoding="utf-8",
        )
    return True


def _strip_value(raw: str) -> str:
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in ("'", '"'):
        return raw[1:-1].strip()
    if " #" in raw:
        raw = raw.split(" #", 1)[0]
    return raw.strip()


def read_env_assignment(env_path: Path, key: str = FERNET_KEY_NAME) -> str | None:
    """Return the assigned value for ``key`` in the file, or None if absent."""
    if not Path(env_path).is_file():
        return None
    parsed = parse_env_text(Path(env_path).read_text(encoding="utf-8-sig"))
    if key not in parsed:
        return None
    return parsed[key]


def _split_keepends(line: str) -> tuple[str, str]:
    if line.endswith("\r\n"):
        return line[:-2], "\r\n"
    if line.endswith("\n"):
        return line[:-1], "\n"
    return line, ""


def _write_fernet_into_text(text: str, key_value: str) -> str:
    """Insert or fill ``ATTESTRA_CREDENTIAL_FERNET_KEY`` without clobbering a real value."""
    lines = text.splitlines(keepends=True)
    if not lines:
        return f"# Auto-generated by attestra env bootstrap. Do not commit.\n{FERNET_KEY_NAME}={key_value}\n"

    # Prefer an empty active assignment; else the first commented assignment.
    fill_idx: int | None = None
    comment_idx: int | None = None
    for i, line in enumerate(lines):
        body, _ = _split_keepends(line)
        m = _ASSIGN_RE.match(body)
        if m:
            if _strip_value(m.group("value")):
                # Already set in the file text; caller should not generate, but stay no-op.
                return text
            if fill_idx is None:
                fill_idx = i
            continue
        if comment_idx is None and _COMMENTED_ASSIGN_RE.match(body):
            comment_idx = i

    target = fill_idx if fill_idx is not None else comment_idx
    out: list[str] = []
    if target is None:
        suffix = "" if text.endswith("\n") or text.endswith("\r\n") else "\n"
        return (
            text
            + suffix
            + f"\n# Auto-generated by attestra env bootstrap. Do not commit.\n{FERNET_KEY_NAME}={key_value}\n"
        )

    for i, line in enumerate(lines):
        body, newline = _split_keepends(line)
        if i == target:
            prefix = ""
            m = _ASSIGN_RE.match(body)
            if m:
                prefix = m.group("prefix")
            else:
                cm = _COMMENTED_ASSIGN_RE.match(body)
                prefix = cm.group("prefix") if cm else ""
            out.append(f"{prefix}{FERNET_KEY_NAME}={key_value}{newline}")
            continue
        # Drop other empty active/commented duplicates of the same key.
        m = _ASSIGN_RE.match(body)
        if m and not _strip_value(m.group("value")):
            continue
        if _COMMENTED_ASSIGN_RE.match(body):
            continue
        out.append(line)
    return "".join(out)


def ensure_credential_fernet_key(
    env_path: Path | str | None = None,
    *,
    example_path: Path | str | None = None,
    set_environ: bool = True,
) -> EnsureFernetResult:
    """Ensure ``.env`` exists and holds a Fernet key for credential encryption.

    Idempotent: an existing non-empty ``ATTESTRA_CREDENTIAL_FERNET_KEY`` is left alone.
    When ``set_environ`` is true and the process env lacks the key, the file value is
    applied to ``os.environ`` (without overriding a non-empty process value).
    """
    path = Path(env_path) if env_path is not None else default_env_path()
    example = Path(example_path) if example_path is not None else default_example_path()
    created = ensure_env_file(path, example_path=example)

    existing = (read_env_assignment(path, FERNET_KEY_NAME) or "").strip()
    generated = False
    if existing:
        key_value = existing
        already_set = True
    else:
        key_value = generate_fernet_key()
        text = path.read_text(encoding="utf-8-sig") if path.is_file() else ""
        path.write_text(_write_fernet_into_text(text, key_value), encoding="utf-8")
        generated = True
        already_set = False

    if set_environ:
        current = (os.environ.get(FERNET_KEY_NAME) or "").strip()
        if not current:
            os.environ[FERNET_KEY_NAME] = key_value

    return EnsureFernetResult(
        env_path=path.resolve(),
        created_env_file=created,
        generated=generated,
        already_set=already_set,
    )


def _key_patterns(key: str) -> tuple[re.Pattern[str], re.Pattern[str]]:
    assign = re.compile(
        rf"^(?P<prefix>\s*(?:export\s+)?)(?P<key>{re.escape(key)})\s*=\s*(?P<value>.*)$"
    )
    commented = re.compile(
        rf"^(?P<prefix>\s*)#\s*(?:export\s+)?(?P<key>{re.escape(key)})\s*=\s*(?P<value>.*)$"
    )
    return assign, commented


def upsert_env_key(text: str, key: str, value: str, *, replace_if: set[str] | None = None) -> tuple[str, bool]:
    """Set ``key=value`` when missing, empty, or equal to ``replace_if``.

    Returns ``(new_text, changed)``. A different non-empty value is left as-is.
    """
    replace_if = replace_if or set()
    assign, commented = _key_patterns(key)
    lines = text.splitlines(keepends=True)
    if not lines:
        return f"{key}={value}\n", True

    fill_idx: int | None = None
    comment_idx: int | None = None
    for i, line in enumerate(lines):
        body, _ = _split_keepends(line)
        m = assign.match(body)
        if m:
            existing = _strip_value(m.group("value"))
            if existing and existing not in replace_if:
                return text, False
            if fill_idx is None:
                fill_idx = i
            continue
        if comment_idx is None and commented.match(body):
            comment_idx = i

    target = fill_idx if fill_idx is not None else comment_idx
    if target is None:
        suffix = "" if text.endswith(("\n", "\r\n")) else "\n"
        return text + suffix + f"{key}={value}\n", True

    out: list[str] = []
    for i, line in enumerate(lines):
        body, newline = _split_keepends(line)
        if i == target:
            prefix = ""
            m = assign.match(body) or commented.match(body)
            if m:
                prefix = m.group("prefix")
            out.append(f"{prefix}{key}={value}{newline}")
            continue
        m = assign.match(body)
        if m and (not _strip_value(m.group("value")) or _strip_value(m.group("value")) in replace_if):
            continue
        if commented.match(body):
            continue
        out.append(line)
    return "".join(out), True


def generate_secret(nbytes: int = 32) -> str:
    return secrets.token_urlsafe(nbytes)


@dataclass(frozen=True)
class EnsureLocalTestingResult:
    """Outcome of [[ensure_local_testing_env]]."""

    env_path: Path
    created_env_file: bool
    changed_keys: tuple[str, ...]


def ensure_local_testing_env(
    env_path: Path | str | None = None,
    *,
    example_path: Path | str | None = None,
    data_dir: Path | str | None = None,
) -> EnsureLocalTestingResult:
    """Fill recommended local Compose flags and secrets without clobbering real values.

    Generates Fernet, session secret, and API pepper when missing or still the
    insecure Compose defaults. Sets auth-web, automated VAPT, credits, public URL,
    auth secret dir, and the absolute host data path when those are empty.
    """
    path = Path(env_path) if env_path is not None else default_env_path()
    example = Path(example_path) if example_path is not None else default_example_path()
    created = ensure_env_file(path, example_path=example)
    text = path.read_text(encoding="utf-8-sig") if path.is_file() else ""
    changed: list[str] = []

    secrets_to_set = {
        FERNET_KEY_NAME: generate_fernet_key(),
        SESSION_SECRET_NAME: generate_secret(),
        API_KEY_PEPPER_NAME: generate_secret(),
    }
    for key, value in secrets_to_set.items():
        replace = {INSECURE_DEFAULTS[key]} if key in INSECURE_DEFAULTS else set()
        # Fernet has no insecure default; empty/missing only.
        text2, did = upsert_env_key(text, key, value, replace_if=replace)
        if did:
            text = text2
            changed.append(key)

    flags = dict(LOCAL_TESTING_FLAGS)
    host_data = Path(data_dir) if data_dir is not None else (path.parent / "data")
    flags["ATTESTRA_DOCKER_HOST_DATA_DIR"] = str(host_data.resolve())
    for key, value in flags.items():
        text2, did = upsert_env_key(text, key, value)
        if did:
            text = text2
            changed.append(key)

    if changed or created:
        path.write_text(text, encoding="utf-8")
    return EnsureLocalTestingResult(
        env_path=path.resolve(),
        created_env_file=created,
        changed_keys=tuple(changed),
    )
