def _xml(data: bytes, part: str = "word/document.xml") -> str:
    with zipfile.ZipFile(BytesIO(data)) as z:
        return z.read(part).decode()


def _all_xml(data: bytes) -> str:
    with zipfile.ZipFile(BytesIO(data)) as z:
        return " ".join(z.read(n).decode("utf-8", "replace") for n in z.namelist() if n.endswith(".xml"))


def test_title_case_keeps_acronyms_and_refs():
    assert title_case("no exceptions") == "No Exceptions"
    assert title_case("not assessed") == "Not Assessed"
    assert title_case("pci dss evidence pack") == "PCI DSS Evidence Pack"
    assert title_case("cvss score and owasp top 10") == "CVSS Score and OWASP Top 10"
    assert title_case("HarmonyPM demo") == "HarmonyPM Demo"
    assert title_case("1.2.1") == "1.2.1"
    assert is_label("proposed") and not is_label("Testing found no exceptions; the assessor must confirm it.")


def test_structure_styles_and_furniture():
    data = render_docx(HTML, kind="technical", draft=True)
    d = docx.Document(BytesIO(data))
    styles = [p.style.name for p in d.paragraphs]
    assert "Title" in styles and "Heading 1" in styles and "Heading 2" in styles
    heads = [p.text for p in d.paragraphs if p.style.name.startswith("Heading")]
    assert "1. Document Control" in heads and any(h.startswith("F-1") for h in heads)
    body = _xml(data)
    assert "TOC \\o" in body  # real TOC field
    assert d.styles["Normal"].font.name == "Calibri"
    allx = _all_xml(data)
    assert "PAGE" in allx and "NUMPAGES" in allx  # Page X of Y
    assert "AttestraDraftWatermark" in allx and "DRAFT" in allx
    assert d.sections[0].different_first_page_header_footer


def test_badges_tiles_and_tables():
    data = render_docx(HTML, kind="technical", draft=True)
    body = _xml(data)
    assert 'w:fill="1F3A5F"' in body  # shaded header row
    assert "w:tblHeader" in body  # repeats on each page
    assert "w:tblCellSpacing" in body  # spaced tiles
    assert 'w:fill="64748B"' in body  # not-assessed badge cell
    assert 'w:fill="A1161B"' in body  # critical badge
    text = docx_text(data)
    for label in ("No Exceptions", "Not Assessed", "Proposed", "Met", "Controls", "Critical", "New", "Draft"):
        assert label in text, label
    assert "no exceptions" not in text and "not assessed" not in text
    assert "<w:drawing" in body  # evidence image embedded


def test_content_complete_vs_html():
    data = render_docx(HTML, kind="technical", draft=True)
    text = docx_text(data).lower()
    for word in ("uniquewordalpha", "x-frame-options", "acme corp", "risk 9.1", "confidential"):
        assert word in text, word


def test_signed_has_no_watermark_and_letter_has_no_cover():
    letter = "<html><body><div class='meta'><span class='brand'>ATTESTRA</span> · Acme</div><h1>Closure letter</h1><p>Dear client.</p></body></html>"
    data = render_docx(letter, kind="closure_letter", draft=False)
    allx = _all_xml(data)
    assert "AttestraDraftWatermark" not in allx
    d = docx.Document(BytesIO(data))
    assert not any(p.style.name == "Title" for p in d.paragraphs)
    assert d.paragraphs and "Closure Letter" in [p.text for p in d.paragraphs]


@pytest.mark.parametrize("kind", ["technical", "executive", "compliance", "iso_soa", "ageing",
                                  "closure_letter", "attestation_letter", "retest"])
def test_every_kind_renders(kind):
    data = render_docx(HTML, kind=kind, draft=True)
    assert data[:2] == b"PK"
    assert re.search(r"Uniquewordalpha", docx_text(data))
